def is_promise_only(text: str) -> bool:
    """Похоже ли сообщение на обещание начать работу без самого результата."""
    raw = (text or "").strip()
    if not raw or len(raw) > 320:
        return False
    low = raw.lower()
    if any(marker in low for marker in _RESULT_MARKERS):
        return False
    if _PROMISE_RE.search(low):
        return True
    # «Секунду, сейчас запустим!» без явного глагола будущего времени —
    # всё равно отсрочка: проверяем первое предложение
    first = re.split(r"[.!?]", low, maxsplit=1)[0]
    return any(word in first for word in _DEFER_WORDS)


